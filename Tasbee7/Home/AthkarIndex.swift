    /// تجميع الأذكار في أقسام منطقية بناءً على الفهرس
    static func groupSections(_ sections: [AthkarSection]) -> [String: [AthkarSection]] {
        var groups: [String: [AthkarSection]] = [:]
        
        // تجميع كل أذكار في القسم المناسب حسب الفهرس
        for section in sections {
            let sectionName = sectionMap[section.title] ?? "أخرى"
            groups[sectionName, default: []].append(section)
        }
        
        // ترتيب الأذكار داخل كل قسم حسب الفهرس (استخدام cached dictionary)
        for (key, items) in groups {
            groups[key] = items.sorted { s1, s2 in
                let idx1 = indexDictionary[s1.title] ?? Int.max
                let idx2 = indexDictionary[s2.title] ?? Int.max
                return idx1 < idx2
            }
        }
        
        // ترتيب الأقسام حسب ترتيبها في sectionOrder
        var orderedGroups: [String: [AthkarSection]] = [:]
        for sectionName in sectionOrder {
            if let items = groups[sectionName], !items.isEmpty {
                orderedGroups[sectionName] = items
            }
        }
        // إضافة "أخرى" في النهاية إن وجدت
        if let others = groups["أخرى"], !others.isEmpty {
            orderedGroups["أخرى"] = others
        }
        
        return orderedGroups
    }
